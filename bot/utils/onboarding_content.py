from datetime import datetime, timezone, timedelta
from typing import Optional

MSK = timezone(timedelta(hours=3))


def day_number_for(progress) -> int:
    """Номер дня онбординга (1-based) от даты запуска (OnboardingProgress.created_at)."""
    started = progress.created_at.replace(tzinfo=timezone.utc).astimezone(MSK)
    now = datetime.now(MSK)
    return max(1, (now.date() - started.date()).days + 1)

