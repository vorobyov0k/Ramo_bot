def get_phase_for_day(day_number: int) -> Optional[dict]:
    for phase in PHASES:
        lo, hi = phase["range"]
        if lo <= day_number <= hi:
            return phase
    return None


def get_all_item_keys() -> list:
    keys = []
    for phase in PHASES:
        keys += [key for key, _ in phase["items"]]
    return keys


