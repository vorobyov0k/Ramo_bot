# db drink ids with zero source-table counterpart — composition/description left untouched, decision needed
DB_ORPHAN_IDS = [31, 41, 59, 60, 65]


def main():
    conn = sqlite3.connect(DB_PATH)
    cur = conn.cursor()
    cur.execute(
        "SELECT d.id, c.name, d.name, d.composition, d.description "
        "FROM drinks d JOIN categories c ON d.category_id = c.id ORDER BY d.id"
    )
    db_rows = {r[0]: r for r in cur.fetchall()}
    conn.close()

    matched_ids = set(MATCHES.values())

    print(f"=== MATCHED ({len(MATCHES)}) ===")
    for (src_cat, src_name), db_id in sorted(MATCHES.items(), key=lambda kv: kv[1]):
        row = db_rows.get(db_id)
        flag = " [NEEDS_REVIEW]" if db_id in REVIEW_REASONS else ""
        print(f"id={db_id:>3} [{src_cat}] '{src_name}' <-> DB '{row[2]}'{flag}")

    print(f"\n=== NEEDS_REVIEW ({len(REVIEW_REASONS)}) ===")
    for db_id, reason in sorted(REVIEW_REASONS.items()):
        print(f"id={db_id}: {reason}")

    db_all_ids = set(db_rows.keys())
    unaccounted = db_all_ids - matched_ids - set(DB_ORPHAN_IDS)
    print(f"\n=== DB_ORPHANS (no source-table match, {len(DB_ORPHAN_IDS)}) ===")
    for db_id in DB_ORPHAN_IDS:
        row = db_rows.get(db_id)
        print(f"id={db_id}: [{row[1]}] '{row[2]}'")

    if unaccounted:
        print(f"\n!!! UNACCOUNTED DB ROWS ({len(unaccounted)}) — bug in matching table, fix before proceeding !!!")
        for db_id in sorted(unaccounted):
            row = db_rows.get(db_id)
            print(f"id={db_id}: [{row[1]}] '{row[2]}'")

    print(f"\nSource items: {len(SOURCE_ITEMS)} | Matched: {len(MATCHES)} | DB rows: {len(db_rows)} | DB orphans: {len(DB_ORPHAN_IDS)}")


if __name__ == "__main__":
    main()
