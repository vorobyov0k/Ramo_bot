def main():
    conn = sqlite3.connect(DB_PATH)
    cur = conn.cursor()
    cur.execute(
        "SELECT d.id, cat.name, d.name, d.composition FROM dishes d JOIN categories cat ON d.category_id = cat.id WHERE cat.type='kitchen' ORDER BY d.id"
    )
    db_rows = {r[0]: r for r in cur.fetchall()}
    conn.close()

    matched_ids = set(MATCHES.values())

    print(f"=== MATCHED ({len(MATCHES)}) ===")
    for src_name, db_id in sorted(MATCHES.items()):
        row = db_rows.get(db_id)
        if row:
            print(f"id={db_id:>3} '{src_name}' <-> DB '{row[2]}'")
        else:
            print(f"id={db_id:>3} '{src_name}' !!! DB id not found")

    print(f"\n=== COMPONENTS (skip, not standalone dishes, {len(COMPONENT_ITEMS)}) ===")
    for name in COMPONENT_ITEMS:
        print(f"  - {name}")

    db_all_ids = set(db_rows.keys())
    unmapped = db_all_ids - matched_ids
    print(f"\n=== DB_UNMAPPED (no tech card, {len(unmapped)}) ===")
    for db_id in sorted(unmapped):
        row = db_rows.get(db_id)
        print(f"id={db_id:>3}: [{row[1]}] '{row[2]}'")

    print(f"\nSource tech cards: {len(SOURCE_TECH_CARDS)} | Matched: {len(MATCHES)} | Components: {len(COMPONENT_ITEMS)} | DB total: {len(db_rows)} | DB unmapped: {len(unmapped)}")


if __name__ == "__main__":
    main()
